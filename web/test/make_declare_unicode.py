"""Writes the Worker's Unicode 16 tables for the declaration character policy (web/src/door/unicode16.js) and the API's
own verdict for every code point (web/test/fixtures/door-a4/declaration-text-u16.json), both from this tree's API.

The Worker must judge a declaration's name and reason exactly as the API does (app/door/intake.py
_declaration_text_allowed, which pins unicodedata2==16.0.0). The JavaScript engine's own \\p{...} tables are Unicode
17.0 in Node 22 and in workerd, and they disagree with 16.0 on 4,803 code points (U+20C1, for one, is unassigned in 16
and assigned in 17), so the Worker reads these generated tables instead:
  REFUSED  the general categories the API refuses (intake._REFUSED_DECLARATION_CATEGORIES: Cc, Cf, Co, Cs, Cn, Zl,
           Zp) and its five invisible fillers (intake._REFUSED_DECLARATION_FILLERS)
  MARKS    Mn, Mc and Me, for the run of at most intake._MAX_COMBINING_RUN marks
  FORMAT   Cf, which the reserved-name comparison removes after NFKC
The Default_Ignorable_Code_Point ranges are not generated: each side hard-codes them once (declare.js
DEFAULT_IGNORABLE, intake._DEFAULT_IGNORABLE), and the fixture carries the API's copy so the Worker's is held to it.

The fixture is what the API itself answers for every code point U+0000..U+10FFFF: refused as a one-character field or
not, and, if not, whether it counts as a mark (8 in a row pass, 9 are refused). web/test/door-declaration-u16.test.mjs
holds the Worker to it, code point by code point; app/test_door_declaration_u16.py holds both files to this generator.

    python web/test/make_declare_unicode.py           # rewrite both files
    python web/test/make_declare_unicode.py --check   # exit 1 when either differs from what this tree generates
It needs the API's requirements (requirements-service.txt pins unicodedata2 16.0.0).
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))
import unicodedata2  # noqa: E402

from app.door import intake  # noqa: E402

MODULE = REPO / "web" / "src" / "door" / "unicode16.js"
FIXTURE = REPO / "web" / "test" / "fixtures" / "door-a4" / "declaration-text-u16.json"
GENERATOR = "web/test/make_declare_unicode.py"
CODE_POINTS = range(0x110000)
MARK_CATEGORIES = ("Mn", "Mc", "Me")


def ranges(members) -> list:
    """Sorted, disjoint [first, last] ranges of the code points for which members[cp] is true."""
    found = []
    for cp in CODE_POINTS:
        if not members[cp]:
            continue
        if found and found[-1][1] == cp - 1:
            found[-1][1] = cp
        else:
            found.append([cp, cp])
    return found


def count(table) -> int:
    return sum(last - first + 1 for first, last in table)


def js_table(name: str, what: str, table: list) -> str:
    numbers = [f"0x{value:04X}" for pair in table for value in pair]
    lines, line = [], "  "
    for number in numbers:
        piece = number + ","
        if len(line) + len(piece) + 1 > 120:
            lines.append(line.rstrip())
            line = "  "
        line += piece + " "
    lines.append(line.rstrip())
    return (f"// {what}. {count(table):,} code points in {len(table)} ranges.\n"
            f"export const {name} = Object.freeze([\n" + "\n".join(lines) + "\n]);\n")


def module_text() -> bytes:
    if unicodedata2.unidata_version != "16.0.0":
        raise RuntimeError("the declaration tables are Unicode 16.0.0 (requirements-service.txt)")
    category = [unicodedata2.category(chr(cp)) for cp in CODE_POINTS]
    refused_categories = sorted(intake._REFUSED_DECLARATION_CATEGORIES)
    fillers = sorted(ord(char) for char in intake._REFUSED_DECLARATION_FILLERS)
    refused = ranges([category[cp] in intake._REFUSED_DECLARATION_CATEGORIES or chr(cp) in
                      intake._REFUSED_DECLARATION_FILLERS for cp in CODE_POINTS])
    marks = ranges([category[cp] in MARK_CATEGORIES for cp in CODE_POINTS])
    format_ = ranges([category[cp] == "Cf" for cp in CODE_POINTS])
    version = unicodedata2.unidata_version
    header = "\n".join([
        f"// GENERATED by {GENERATOR} from unicodedata2 {version}; do not edit. To regenerate, run that",
        "// script; app/test_door_declaration_u16.py fails when this file differs from its output.",
        f"// The Unicode tables of the declaration character policy (declare.js), pinned to Unicode {version}. The API",
        f"// judges a name and reason with unicodedata2=={version} (app/door/intake.py); the JavaScript engine's own",
        "// \\p{...} tables are Unicode 17.0 in Node 22 and in workerd. With these tables the Worker judges every code point",
        "// as the API does.",
        f"// Provenance: general categories from unicodedata2 {version} (Unicode Character Database {version}). The",
        f"// refused categories ({', '.join(refused_categories)}) and the five invisible fillers",
        f"// ({', '.join(f'U+{cp:04X}' for cp in fillers)}) are the API's own:",
        "// intake._REFUSED_DECLARATION_CATEGORIES and intake._REFUSED_DECLARATION_FILLERS.",
        "// Each table is sorted, disjoint [first, last] code point ranges, flattened: [first0, last0, first1, last1, ...].",
        f'export const UNICODE_VERSION = "{version}";',
        ""])
    body = "\n".join([
        js_table("REFUSED", f"Refused in a name or reason: {', '.join(refused_categories)}, and the five fillers", refused),
        js_table("MARKS", "Marks (Mn, Mc, Me), for the run rule: more than 8 in a row is refused", marks),
        js_table("FORMAT", "Format characters (Cf), which the reserved-name comparison removes after NFKC", format_),
    ])
    return (header + "\n" + body).encode("ascii")


def fixture_text() -> bytes:
    """The API's own answer for every code point, from intake._declaration_text_allowed itself."""
    allowed = intake._declaration_text_allowed
    run = intake._MAX_COMBINING_RUN
    refused = [not allowed(chr(cp)) for cp in CODE_POINTS]
    marks = [not refused[cp] and allowed(chr(cp) * run) and not allowed(chr(cp) * (run + 1)) for cp in CODE_POINTS]
    ignorable = [list(pair) for pair in intake._DEFAULT_IGNORABLE]
    document = {
        "schema": "sentilab-door-declaration-text-verdicts/1",
        "generator": GENERATOR,
        "rule": "app/door/intake.py _declaration_text_allowed, on each code point alone and as a run",
        "unicode": unicodedata2.unidata_version,
        "max_mark_run": run,
        "refused": {"count": count(ranges(refused)), "ranges": ranges(refused)},
        "marks": {"count": count(ranges(marks)), "ranges": ranges(marks)},
        "default_ignorable": {"source": "DerivedCoreProperties-16.0.0.txt, Default_Ignorable_Code_Point",
                              "count": count(ignorable), "ranges": ignorable},
    }
    text = json.dumps(document, ensure_ascii=True, separators=(",", ":"))
    for key in ('"refused"', '"marks"', '"default_ignorable"'):
        text = text.replace("," + key, ",\n" + key)
    return (text + "\n").encode("ascii")


def generate() -> dict:
    return {MODULE: module_text(), FIXTURE: fixture_text()}


if __name__ == "__main__":
    files = generate()
    if "--check" in sys.argv:
        stale = [path.relative_to(REPO).as_posix() for path, data in files.items()
                 if not path.exists() or path.read_bytes() != data]
        print("stale:", ", ".join(stale) if stale else "none")
        sys.exit(1 if stale else 0)
    for path, data in files.items():
        path.write_bytes(data)
        print("wrote", path.relative_to(REPO).as_posix(), len(data), "bytes")
