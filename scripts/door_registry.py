"""Generate the door's exact registry enums from the bundled AIdenID registry (app/door/aidenid-registry.json, the
public registry fetched 2026-11-01T18:09Z; data only, never executed). One list per field, the same in Python
(app/door/registry_enums.py) and in the Worker (web/src/door/registry-enums.js); anything not on a list is null.

    python -m scripts.door_registry --write    # regenerate both files
    python -m scripts.door_registry --check    # exit 1 if either differs from what the registry gives
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "app" / "door" / "aidenid-registry.json"
PY = ROOT / "app" / "door" / "registry_enums.py"
JS = ROOT / "web" / "src" / "door" / "registry-enums.js"


def enums() -> tuple:
    raw = REGISTRY.read_bytes()
    data = json.loads(raw)
    ids = lambda items: [item["id"] if isinstance(item, dict) else item for item in items]  # noqa: E731
    operators = {}
    for service in data["services"]:
        operators.setdefault(service["operator"], service["operatorName"])
    return (hashlib.sha256(raw).hexdigest(), len(raw), ids(data["services"]), ids(data["categories"]),
            ids(data["verificationLevels"]), operators, {service["id"]: service["name"] for service in data["services"]})


def render() -> dict:
    sha, size, services, categories, levels, operators, names = enums()
    head = (f"the AIdenID registry bundled at app/door/aidenid-registry.json ({size} bytes, sha256 {sha}): "
            f"{len(services)} service ids, {len(categories)} categories, {len(levels)} verification levels")
    py = ('"""Generated by scripts/door_registry.py from ' + head + '.\nAn arrival keeps a value only when it is '
          'exactly one of these; anything else is null. Do not edit by hand."""\n'
          f'REGISTRY_SHA256 = "{sha}"\n'
          + "".join(f"{name} = (\n" + "".join(f'    "{value}",\n' for value in values) + ")\n"
                    for name, values in (("SERVICES", services), ("CATEGORIES", categories),
                                         ("VERIFICATIONS", levels)))
          + "# Display names, so a feed can name what it recognised (the pages bundle no vendor names).\n"
          + "".join(f"{name} = {{\n" + "".join(f"    {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)},\n"
                                                for key, value in values.items()) + "}\n"
                    for name, values in (("OPERATOR_NAMES", operators), ("SERVICE_NAMES", names))))
    js = (f"// Generated by scripts/door_registry.py from {head}.\n// An arrival sends a value only when it is "
          "exactly one of these. Do not edit by hand.\n"
          f'export const REGISTRY_SHA256 = "{sha}";\n'
          + "".join(f"export const {name} = Object.freeze([\n" + "".join(f'  "{value}",\n' for value in values)
                    + "]);\n" for name, values in (("SERVICES", services), ("CATEGORIES", categories),
                                                    ("VERIFICATIONS", levels))))
    return {PY: py.encode("utf-8"), JS: js.encode("utf-8")}


def main(argv) -> int:
    stale = [path.name for path, data in render().items() if not path.exists() or path.read_bytes() != data]
    if "--write" in argv:
        for path, data in render().items():
            path.write_bytes(data)
        return 0
    print("stale: " + ", ".join(stale) if stale else "registry enums match the bundled registry")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
