"""validate-reference (SLAB-049): the only path that may run an evaluator before it has passed gate zero.

It produces the gate-zero receipts, so it cannot require a prior PASS; that would be circular. The entry point
refuses anything the frozen manifest (docs/sentilab/diagnostics/SLAB-049/CALL-LIST.json) does not list:

- only a listed call id, with the listed engine, reference and grid;
- only before the window closes and on the listed architecture;
- each call once (the grant's ledger reserves it);
- under a CPU cap (RLIMIT_CPU on the solver process) as well as a wall timeout.

The inputs are regenerated by TAP's own generator into a fresh, empty directory (so the config is written fresh,
never reused) and must match the frozen inputs byte for byte. The reservation and identity are written before
launch, and the receipt is settled on every exit path, with the raw outputs kept. Search and headroom go through
evaluators.make_oracle, which refuses without a PASS receipt.

    python -m sundai_hotspot.reference_validation validate-reference --call p-hs6-ascend910-original-g64 \\
        --out FRESH_DIR --ledger GRANT_LEDGER_DIR [--binary PATH]
    python -m sundai_hotspot.reference_validation record --kind hotspot6 [--binary PATH] \\
        --run ascend910-original-snapped=DIR --run micro150-original-snapped=DIR --out RECORD.json
    python -m sundai_hotspot.reference_validation report --run DIR [--run DIR ...] --out REPORT.json

Running validate-reference is a thermal solve. It needs warden's grant. `record` and `report` only read files.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import platform
import subprocess
import sys
import time

from sundai_hotspot import gate_zero, slab049
from sundai_hotspot.tap_oracle import REPO_ROOT

MANIFEST_PATH = slab049.EVIDENCE_DIR / "CALL-LIST.json"
# aneta-claude's independent network model (#56739) predicts these grid 32 -> 64 changes in the block-centre peak
# on HotSpot 6.0. Context for the report only: nothing is frozen on them, nor on the old mesh error.
NETWORK_MODEL_MESH_DELTA_K = {"ascend910": 0.01, "micro150": 0.18}
OLD_HOTSPOT7_MESH_ERROR_K = {"ascend910": 0.16, "micro150": 0.79}


class CallRefused(RuntimeError):
    """The requested call is not what the frozen manifest allows."""


def _sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _children_cpu_s() -> float:
    import resource
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def _reference(reference_id: str) -> tuple[gate_zero.Reference, str, str]:
    pinned = {r.id: r for r in gate_zero.REFERENCES}
    if reference_id not in pinned or pinned[reference_id].inputs is None:
        raise CallRefused(f"{reference_id!r} is not a frozen pinned reference")
    reference = pinned[reference_id]
    layout, variant = Path(reference.inputs).name.removesuffix("-45mm").rsplit("-", 1)
    return reference, layout, variant


def stage(reference_id: str, out: Path) -> dict[str, str]:
    """Write the reference inputs fresh into the call's new directory and check them against the frozen hashes.

    validate_call has already refused a non-empty directory; the only file there is the call's own receipt.
    """
    reference, layout, variant = _reference(reference_id)
    out = Path(out)
    if any(path.name != "receipt.json" for path in out.iterdir()):
        raise CallRefused(f"{out} holds files other than this call's receipt; every call needs a fresh directory")
    files = slab049.generate_reference(slab049.reference_spec(layout, variant), out)
    for name, data in files.items():  # local LCF paths and LF line ends, as frozen
        (out / name).write_bytes(data)
    frozen = gate_zero.frozen_inputs(reference)
    staged = {name: _sha256(out / name) for name in frozen}
    if staged != frozen:
        raise CallRefused(f"{reference_id}: fresh inputs differ from the frozen ones: "
                          f"{sorted(n for n in frozen if staged[n] != frozen[n])}")
    return staged


def admit(call_id: str, manifest: dict, *, kind: str | None = None, reference: str | None = None,
          grid: int | None = None, timeout_s: float | None = None, now: datetime | None = None) -> dict:
    """Refuse anything the manifest does not list. Optional arguments must equal the call's listed values."""
    if os.name != "posix":
        raise CallRefused("validate-reference needs POSIX: the CPU cap is RLIMIT_CPU on the solver process")
    calls = {c["id"]: c for c in manifest.get("calls", [])}
    if call_id not in calls:
        raise CallRefused(f"{call_id!r} is not a call in the frozen manifest")
    call = calls[call_id]
    for name, given, listed in (("engine", kind, call["kind"]), ("reference", reference, call["reference"]),
                                ("grid", grid, call["grid"])):
        if given is not None and given != listed:
            raise CallRefused(f"{call_id}: {name} {given!r} is not the listed {listed!r}")
    if timeout_s is not None and timeout_s > call["accounting"]["cpu_cap_s"]:
        raise CallRefused(f"{call_id}: a {timeout_s} s timeout exceeds the listed {call['accounting']['cpu_cap_s']} s cap")
    deadline = datetime.fromisoformat(manifest["grant_window"]["not_after_utc"].replace("Z", "+00:00"))
    if (now or _now()) > deadline:
        raise CallRefused(f"the grant window closed at {deadline.isoformat()}")
    architecture = manifest["accounting"]["host_architecture"]
    if platform.machine() != architecture:
        raise CallRefused(f"this host is {platform.machine()}; the manifest lists {architecture}")
    return call


def _reserve(ledger: Path, call: dict, payload: dict) -> Path:
    """Exclusive, write-once reservation: a call that was reserved before is refused (no second run)."""
    ledger.mkdir(parents=True, exist_ok=True)
    path = ledger / f"{call['id']}.reserved.json"
    try:
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o444)
    except FileExistsError as exc:
        raise CallRefused(f"{call['id']} was already reserved in this ledger; calls are not retried") from exc
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    return path


def _write_receipt(out: Path, receipt: dict) -> None:
    temporary = out / "receipt.json.tmp"
    temporary.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(temporary, out / "receipt.json")


def validate_call(call_id: str, out: Path, ledger: Path, *, binary: Path | None = None,
                  manifest: dict | None = None, kind: str | None = None, reference: str | None = None,
                  grid: int | None = None, timeout_s: float | None = None, now: datetime | None = None) -> dict:
    """Run one listed call in a fresh process and settle its receipt. Needs no prior gate-zero PASS."""
    manifest_bytes = MANIFEST_PATH.read_bytes()
    manifest = manifest if manifest is not None else json.loads(manifest_bytes)
    call = admit(call_id, manifest, kind=kind, reference=reference, grid=grid, timeout_s=timeout_s, now=now)
    binary = Path(binary or REPO_ROOT / call["binary"]).resolve()
    identity = gate_zero.evaluator_identity(call["kind"], binary)
    pinned, _, _ = _reference(call["reference"])
    out = Path(out)
    cap = float(call["accounting"]["cpu_cap_s"])
    argv = slab049.tap_argv(str(binary), call["grid"])
    receipt = {
        "schema": gate_zero.RECEIPT_SCHEMA, "call": call_id, "manifest_sha256": hashlib.sha256(manifest_bytes).hexdigest(),
        "evaluator": identity, "reference": pinned.id, "role": pinned.role, "paper_c": pinned.paper_c,
        "grid": call["grid"], "argv": argv, "temperature_label": gate_zero.TEMPERATURE_LABELS[call["kind"]],
        "cpu_cap_s": cap, "wall_timeout_s": 2 * cap, "host": {"architecture": platform.machine(),
                                                             "node": platform.node()},
        "reserved_utc": (now or _now()).isoformat(), "status": "reserved",
    }
    if out.exists() and any(out.iterdir()):
        raise CallRefused(f"{out} is not empty; every call needs a fresh directory")
    out.mkdir(parents=True, exist_ok=True)
    _reserve(Path(ledger), call, {**receipt, "out": str(out.resolve())})
    _write_receipt(out, receipt)  # identity and reservation are on disk before anything else runs

    def limit_cpu():
        import resource
        seconds = math.ceil(cap)
        resource.setrlimit(resource.RLIMIT_CPU, (seconds, seconds + 1))

    started = _now()
    cpu_before, clock = _children_cpu_s(), time.perf_counter()
    try:
        receipt["inputs"] = stage(call["reference"], out)
        receipt["config_sha256"] = receipt["inputs"]["new_hotspot.config"]
        _write_receipt(out, receipt)
        solver_cpu_before = _children_cpu_s()
        with (out / "stdout.txt").open("wb") as stdout, (out / "stderr.txt").open("wb") as stderr:
            process = subprocess.run(argv, cwd=out, stdout=stdout, stderr=stderr, timeout=2 * cap, check=False,
                                     preexec_fn=limit_cpu)
        receipt["solver_cpu_s"] = _children_cpu_s() - solver_cpu_before
        receipt["exit_status"] = process.returncode
        receipt["status"] = ("exited" if process.returncode >= 0 else
                             "cpu_cap" if -process.returncode in (24, 9) else "signalled")
    except subprocess.TimeoutExpired:
        receipt["status"], receipt["exit_status"] = "wall_timeout", None
    except OSError as exc:
        receipt["status"] = "launch_error" if "inputs" in receipt else "stage_error"
        receipt["exit_status"], receipt["error"] = None, repr(exc)
    except BaseException as exc:  # settle the receipt, then let the caller see the failure
        receipt["status"] = "error" if "inputs" in receipt else "stage_error"
        receipt["exit_status"], receipt["error"] = None, f"{type(exc).__name__}: {exc}"
        raise
    finally:
        receipt["started_utc"], receipt["finished_utc"] = started.isoformat(), _now().isoformat()
        receipt["wall_s"] = time.perf_counter() - clock
        receipt["children_cpu_s"] = _children_cpu_s() - cpu_before
        receipt["outputs"] = {name: _sha256(out / name) for name in gate_zero.RECEIPT_OUTPUTS if (out / name).is_file()}
        if receipt["status"] == "exited" and receipt["exit_status"] == 0:
            try:
                receipt["solve_record"] = slab049.summarize_evaluation(
                    out, grid_size=call["grid"], grid_format=gate_zero.GRID_FORMATS[call["kind"]])
            except Exception as exc:  # the raw outputs stay; the receipt says why the record failed
                receipt["status"], receipt["error"] = "record_error", f"{type(exc).__name__}: {exc}"
        _write_receipt(out, receipt)
        (Path(ledger) / f"{call_id}.settled.json").write_text(
            json.dumps({k: receipt.get(k) for k in ("call", "status", "exit_status", "started_utc", "finished_utc",
                                                    "wall_s", "children_cpu_s", "solver_cpu_s", "outputs")},
                       indent=2, sort_keys=True)
            + "\n", encoding="utf-8")
    return receipt


def report(run_dirs: list[Path]) -> dict:
    """From the manifest's run directories, without any extra call (reads receipts and outputs only):

    - HotSpot 6.0's grid 32 -> 64 change per fixture, on the block-centre metric and the grid peak;
    - CPU seconds per call, per engine;
    - whether every replay's outputs are byte-identical to its primary call's;
    - the same-index spreader-sink drop per run (reported, not asserted).
    """
    groups: dict[tuple[str, str], dict] = {}
    for directory in run_dirs:
        receipt = json.loads((Path(directory) / "receipt.json").read_text(encoding="utf-8"))
        key = (receipt["evaluator"]["kind"], receipt["reference"])
        group = groups.setdefault(key, {"grids": {}, "replays": [], "cpu_s": []})
        group["cpu_s"].append({"call": receipt.get("call"), "solver_cpu_s": receipt.get("solver_cpu_s"),
                               "call_cpu_s": receipt.get("children_cpu_s")})
        if receipt.get("status") != "exited" or receipt.get("exit_status") != 0:
            group.setdefault("failed", []).append({"call": receipt.get("call"), "status": receipt.get("status")})
            continue
        record = receipt.get("solve_record", {})
        entry = {"selector_c": gate_zero.tap_selector_c(Path(directory) / "sample.steady")[0],
                 "grid_peak_c": record.get("active_layer_grid_peak", {}).get("peak_C"),
                 "steady_sha256": receipt["outputs"].get("sample.steady"),
                 "grid_sha256": receipt["outputs"].get("sample.grid.steady"),
                 "drop": record.get("spreader_sink_drop_diagnostic")}
        if (receipt.get("call") or "").startswith("r-"):
            group["replays"].append(entry)
        else:
            group["grids"][receipt["grid"]] = entry
    rows = []
    for (kind, reference), group in sorted(groups.items()):
        fixture = reference.split("-")[0]
        g32, g64 = group["grids"].get(32), group["grids"].get(64)
        both = g32 is not None and g64 is not None
        rows.append({
            "kind": kind, "reference": reference, "temperature_label": gate_zero.TEMPERATURE_LABELS[kind],
            "block_centre_c": {str(g): e["selector_c"] for g, e in group["grids"].items()},
            "grid32_to_64_block_centre_delta_k": (g64["selector_c"] - g32["selector_c"]) if both else None,
            "grid32_to_64_grid_peak_delta_k": ((g64["grid_peak_c"] - g32["grid_peak_c"])
                                               if both and None not in (g32["grid_peak_c"], g64["grid_peak_c"]) else None),
            "network_model_prediction_k": NETWORK_MODEL_MESH_DELTA_K.get(fixture) if kind.startswith("hotspot6") else None,
            "old_hotspot7_mesh_error_k": OLD_HOTSPOT7_MESH_ERROR_K.get(fixture),
            "replays_byte_identical": (all(r["steady_sha256"] == g64["steady_sha256"] and r["grid_sha256"] == g64["grid_sha256"]
                                           for r in group["replays"]) if g64 and group["replays"] else None),
            "cpu_s_per_call": group["cpu_s"],
            "spreader_sink_drop_g64": g64["drop"] if g64 else None,
            "failed_calls": group.get("failed", []),
        })
    return {"schema": "sentilab-slab049-manifest-report-v1", "rows": rows,
            "note": "nothing here is frozen as a mesh error; the next protocol sets its own"}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("validate-reference")
    record = sub.add_parser("record")
    summary = sub.add_parser("report")
    run.add_argument("--call", required=True)
    run.add_argument("--ledger", type=Path, required=True)
    run.add_argument("--binary", type=Path)
    run.add_argument("--kind")
    run.add_argument("--reference")
    run.add_argument("--grid", type=int)
    run.add_argument("--timeout", type=float)
    record.add_argument("--kind", required=True, choices=sorted(gate_zero.EVALUATOR_KINDS))
    record.add_argument("--binary", type=Path)
    record.add_argument("--run", action="append", default=[], help="REFERENCE=DIR, one per validated reference")
    summary.add_argument("--run", action="append", default=[], type=Path, help="a run directory, repeated")
    for command in (run, record, summary):
        command.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    if args.command == "report":
        args.out.write_text(json.dumps(report(args.run), indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return 0
    if args.command == "validate-reference":
        try:
            receipt = validate_call(args.call, args.out, args.ledger, binary=args.binary, kind=args.kind,
                                    reference=args.reference, grid=args.grid, timeout_s=args.timeout)
        except CallRefused as exc:
            print(f"refused: {exc}", file=sys.stderr)
            return 2
        print(json.dumps({k: receipt.get(k) for k in ("call", "status", "exit_status", "wall_s", "children_cpu_s")}))
        return 0 if receipt["status"] == "exited" and receipt["exit_status"] == 0 else 1
    binary = args.binary or REPO_ROOT / gate_zero.EVALUATOR_KINDS[args.kind]["binary"]
    runs = dict(item.split("=", 1) for item in args.run)
    result = gate_zero.build_record(args.kind, binary, {k: Path(v) for k, v in runs.items()})
    args.out.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(result["verdict"])
    return 0 if result["verdict"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
