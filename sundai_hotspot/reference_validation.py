"""validate-reference (SLAB-049): the only path that may run an evaluator before it has passed gate zero.

It produces the gate-zero receipts, so it cannot require a prior PASS; that would be circular. It runs only a
pinned reference layout. The inputs are regenerated by TAP's own generator into a fresh, empty directory (so the
config is written fresh, never reused) and must match the frozen inputs byte for byte. Search and headroom go
through evaluators.make_oracle, which refuses without a PASS receipt.

    python -m sundai_hotspot.reference_validation validate-reference --kind hotspot6 \\
        --reference ascend910-original-snapped --grid 64 --out FRESH_DIR [--binary PATH] [--timeout S] [--call ID]
    python -m sundai_hotspot.reference_validation record --kind hotspot6 [--binary PATH] \\
        --run ascend910-original-snapped=DIR --run micro150-original-snapped=DIR --out RECORD.json

Running this module is a thermal solve. It needs a grant; the SLAB-049 manifest lists the allowed calls.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time

from sundai_hotspot import gate_zero, slab049
from sundai_hotspot.tap_oracle import REPO_ROOT

OUTPUTS = ("stdout.txt", "stderr.txt", "sample.steady", "sample.grid.steady")


def _sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _children_cpu_s() -> float | None:
    try:
        import resource
    except ImportError:  # not POSIX: the receipt records CPU as unmeasured, never as zero
        return None
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def _reference(reference_id: str) -> tuple[gate_zero.Reference, str, str]:
    pinned = {r.id: r for r in gate_zero.REFERENCES}
    if reference_id not in pinned:
        raise ValueError(f"unknown reference {reference_id!r}; pinned: {sorted(pinned)}")
    reference = pinned[reference_id]
    if reference.inputs is None:
        raise ValueError(f"{reference_id} is pending; its layout is not frozen")
    stem = Path(reference.inputs).name.removesuffix("-45mm")
    layout, variant = stem.rsplit("-", 1)
    return reference, layout, variant


def stage(reference_id: str, out: Path) -> dict[str, str]:
    """Write the reference inputs fresh into an empty directory and check them against the frozen hashes."""
    reference, layout, variant = _reference(reference_id)
    out = Path(out)
    if out.exists() and any(out.iterdir()):
        raise ValueError(f"{out} is not empty; every call needs a fresh directory")
    out.mkdir(parents=True, exist_ok=True)
    files = slab049.generate_reference(slab049.reference_spec(layout, variant), out)
    for name, data in files.items():  # local LCF paths and LF line ends, as frozen
        (out / name).write_bytes(data)
    frozen = gate_zero.frozen_inputs(reference)
    staged = {name: _sha256(out / name) for name in frozen}
    if staged != frozen:
        raise ValueError(f"{reference_id}: fresh inputs differ from the frozen ones: "
                         f"{sorted(n for n in frozen if staged[n] != frozen[n])}")
    return staged


def validate_reference(kind: str, binary: Path, reference_id: str, grid: int, out: Path, *,
                       timeout_s: float = 60.0, call_id: str | None = None) -> dict:
    """One fresh-process solve of a pinned reference, and its receipt. Needs no prior gate-zero PASS."""
    identity = gate_zero.evaluator_identity(kind, binary)
    reference, _, _ = _reference(reference_id)
    out = Path(out)
    inputs = stage(reference_id, out)
    argv = slab049.tap_argv(str(Path(binary).resolve()), grid)
    started = datetime.now(timezone.utc)
    cpu_before, clock = _children_cpu_s(), time.perf_counter()
    status, exit_status = "exited", None
    with (out / "stdout.txt").open("wb") as stdout, (out / "stderr.txt").open("wb") as stderr:
        try:
            exit_status = subprocess.run(argv, cwd=out, stdout=stdout, stderr=stderr, timeout=timeout_s,
                                         check=False).returncode
        except subprocess.TimeoutExpired:
            status = "timeout"
    wall_s = time.perf_counter() - clock
    cpu_after = _children_cpu_s()
    finished = datetime.now(timezone.utc)
    receipt = {
        "schema": gate_zero.RECEIPT_SCHEMA, "call": call_id, "evaluator": identity, "reference": reference.id,
        "role": reference.role, "paper_c": reference.paper_c, "grid": grid, "argv": argv, "inputs": inputs,
        "config_sha256": inputs["new_hotspot.config"],
        "started_utc": started.isoformat(), "finished_utc": finished.isoformat(), "wall_s": wall_s,
        "children_cpu_s": None if cpu_before is None or cpu_after is None else cpu_after - cpu_before,
        "status": status, "exit_status": exit_status, "timeout_s": timeout_s,
        "outputs": {name: _sha256(out / name) for name in OUTPUTS if (out / name).is_file()},
    }
    if status == "exited" and exit_status == 0:
        receipt["solve_record"] = slab049.summarize_evaluation(out, grid_size=grid)
    (out / "receipt.json").write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return receipt


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("validate-reference")
    record = sub.add_parser("record")
    for command in (run, record):
        command.add_argument("--kind", required=True, choices=sorted(gate_zero.EVALUATOR_KINDS))
        command.add_argument("--binary", type=Path)
        command.add_argument("--out", type=Path, required=True)
    run.add_argument("--reference", required=True)
    run.add_argument("--grid", type=int, default=gate_zero.GRID)
    run.add_argument("--timeout", type=float, default=60.0)
    run.add_argument("--call")
    record.add_argument("--run", action="append", default=[], help="REFERENCE=DIR, one per validated reference")
    args = parser.parse_args(argv)
    binary = args.binary or REPO_ROOT / gate_zero.EVALUATOR_KINDS[args.kind]["binary"]
    if args.command == "validate-reference":
        receipt = validate_reference(args.kind, binary, args.reference, args.grid, args.out,
                                     timeout_s=args.timeout, call_id=args.call)
        print(json.dumps({k: receipt[k] for k in ("reference", "grid", "status", "exit_status", "wall_s")}))
        return 0 if receipt["status"] == "exited" and receipt["exit_status"] == 0 else 1
    runs = dict(item.split("=", 1) for item in args.run)
    result = gate_zero.build_record(args.kind, binary, {k: Path(v) for k, v in runs.items()})
    args.out.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(result["verdict"])
    return 0 if result["verdict"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
